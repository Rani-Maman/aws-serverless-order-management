import json
import os
import boto3

s3 = boto3.client("s3")
BUCKET = os.environ["BACKUP_BUCKET"]

CORS_HEADERS = {
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Headers": "Content-Type",
    "Access-Control-Allow-Methods": "OPTIONS,GET,POST,PUT,DELETE",
}


def _response(status, body):
    return {"statusCode": status, "headers": CORS_HEADERS, "body": json.dumps(body, default=str)}


def lambda_handler(event, context):
    """
    Lists all PDF reports auto-generated by the EventBridge schedule
    (`reports/scheduled/`). Returns each entry with a fresh
    pre-signed download URL so the UI can render download links.

    This is the API the "Scheduled Reports" tab in the web client calls.
    """
    try:
        paginator = s3.get_paginator("list_objects_v2")
        reports = []
        for page in paginator.paginate(Bucket=BUCKET, Prefix="reports/scheduled/"):
            for obj in page.get("Contents", []):
                if not obj["Key"].endswith(".pdf"):
                    continue
                url = s3.generate_presigned_url(
                    "get_object",
                    Params={"Bucket": BUCKET, "Key": obj["Key"]},
                    ExpiresIn=3600,
                )
                reports.append({
                    "key": obj["Key"],
                    "last_modified": obj["LastModified"].isoformat(),
                    "size_bytes": obj["Size"],
                    "url": url,
                })
        reports.sort(key=lambda r: r["last_modified"], reverse=True)
        return _response(200, {"count": len(reports), "reports": reports})
    except Exception as e:
        return _response(500, {"error": str(e)})
